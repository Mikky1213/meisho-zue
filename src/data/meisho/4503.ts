御霊屋
徳川家康の生母・伝通院殿の御霊屋である。遺言によって御廟が建てられ、その法号を取って寺も「伝通院」と呼ばれるようになったという。『江戸名所図会』は、遺骸は同じ小石川の宗慶寺に納められたと記す。『和漢三才図会』には、慶長7年（1602）8月29日に亡くなったとある。

